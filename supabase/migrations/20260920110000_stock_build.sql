-- Constituer le stock avant le lancement, et le faire grossir chaque nuit.
--
-- Trois nuits de mesure après la mission V2 : 2 477 opportunités en stock,
-- +25 à +90 par nuit. Quatre bornes expliquaient le plateau :
--
--   1. le moteur d'opportunités et le moteur de signaux ne regardaient que
--      les 20 000 premières entreprises (sur 236 000 signalées), les mêmes
--      chaque nuit — les jobs prennent désormais toute la base en tranches ;
--   2. la recherche de site — dont l'échec est la PREUVE d'absence de site,
--      donc la matière des créations — ne traitait que 200 entreprises par
--      nuit, sans priorité : 3 000 par nuit, les joignables et identifiées
--      d'abord ;
--   3. le scan était ramené au plancher (500 par nuit) dès que le stock
--      dépassait 2 000 et qu'aucun abonné ne consommait : le stock visé,
--      le plancher et le plafond deviennent des réglages ;
--   4. l'identité locale s'arrêtait à 1 000 entreprises par nuit, le backfill
--      des contacts s'était arrêté le 17 septembre (interrompu par un
--      déploiement, jamais relancé) : pages jusqu'à la limite, et une
--      relance chaque nuit sur ce qui est encore en attente.

-- ─── 1. Les réglages ────────────────────────────────────────────────────────

insert into public.engine_settings (key, value, description) values
  ('scan_stock_target', '20000', 'Stock d''opportunités disponibles visé, même sans abonné : la mission de scan cherche à l''atteindre.'),
  ('scan_floor_per_night', '3000', 'Domaines scannés au minimum chaque nuit, quel que soit le stock.'),
  ('scan_max_per_night', '15000', 'Domaines scannés au maximum chaque nuit (hors amorçage).'),
  ('website_resolution_per_night', '3000', 'Entreprises sans site pour lesquelles on cherche un site chaque nuit, joignables et identifiées d''abord.')
on conflict (key) do nothing;

update public.engine_settings set value = '40'
where key = 'discovery_areas_per_night' and (value #>> '{}')::integer < 40;

-- ─── 2. Le backfill des contacts, repris chaque nuit sur ce qui attend ──────

